#!/usr/bin/env python3
"""Render existing partner cards, highest priority first. --check never writes."""
import argparse
import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLOCK = re.compile(r'(?P<start><div class="partners-grid">).*?(?P<end>\n          </div>\n        </div>\n      </section>)', re.S)


def load():
    data = json.loads((ROOT / 'scripts/partners.json').read_text())
    partners = data['partners']
    assert len({p['id'] for p in partners}) == len(partners), 'Duplicate partner ID'
    assert len({p['priority'] for p in partners}) == len(partners), 'Duplicate priority'
    for partner in partners:
        assert type(partner['priority']) is int
        assert partner['url'].startswith('https://')
        assert set(partner['content']) == set(data['pages'])
    return data


def render(partner, lang):
    c = partner['content'][lang]
    # Existing full-card link and contact text convention; never nest anchors.
    paragraphs = '\n'.join('                <p class="partner-card__description">' + text + '</p>'
                           for text in c['descriptions_html'])
    return f'''            <a class="partner-card" href="{escape(partner['url'], quote=True)}" target="_blank" rel="noopener noreferrer">
              <div class="partner-card__image">
                {c['image_html']}
              </div>
              <div class="partner-card__content">
                <h2 class="partner-card__title">{escape(c['title'])}</h2>
{paragraphs}
                <p class="partner-card__badge">{escape(c['badge'])}</p>
              </div>
            </a>'''


def build(check=False):
    data = load()
    partners = sorted(data['partners'], key=lambda p: p['priority'], reverse=True)
    stale = []
    for lang, filename in data['pages'].items():
        path = ROOT / filename
        source = path.read_text()
        body = '\n            <!-- Generated by scripts/build-partners.py from scripts/partners.json. -->\n'
        body += '\n'.join(render(p, lang) for p in partners)
        updated, count = BLOCK.subn(lambda m: m['start'] + body + m['end'], source)
        assert count == 1, filename
        if updated != source:
            stale.append(filename)
            if not check:
                path.write_text(updated)
    print(f'Partners: {len(partners)}; pages: {len(data["pages"])}; {"stale" if check else "updated"}: {len(stale)}')
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = build(args.check)
    if args.check and stale:
        raise SystemExit(1)
