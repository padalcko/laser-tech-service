#!/usr/bin/env python3
"""Render existing partner cards, highest priority first. --check never writes."""
import argparse
import json
import re
from html import escape
from urllib.parse import quote
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLOCK = re.compile(r'(?P<start><div class="partners-grid">).*?(?P<end>\n          </div>\n        </div>\n      </section>)', re.S)


def load():
    data = json.loads((ROOT / 'scripts/partners.json').read_text())
    partners = data['partners']
    assert len({p['id'] for p in partners}) == len(partners), 'Duplicate partner ID'
    assert len({p['priority'] for p in partners}) == len(partners), 'Duplicate priority'
    for partner in partners:
        assert type(partner['priority']) is int
        assert partner['url'].startswith('https://')
        assert set(partner['content']) == set(data['pages'])
    return data


LABELS = {
    'pl': ['Wszyscy', 'Salony kosmetyczne', 'Kliniki', 'Partnerzy biznesowi', 'Zamknij', 'Zadzwoń', 'Wyznacz trasę', 'Strona internetowa'],
    'ru': ['Все', 'Салоны красоты', 'Клиники', 'Бизнес-партнёры', 'Закрыть', 'Позвонить', 'Построить маршрут', 'Веб-сайт'],
    'en': ['All', 'Beauty salons', 'Clinics', 'Business partners', 'Close', 'Call', 'Get directions', 'Website'],
}


def render(partner, lang):
    c = partner['content'][lang]
    labels = LABELS[lang]
    title = escape(c['title'])
    ident = escape(partner['id'], quote=True)
    paragraphs = ''.join('<p class="partner-card__description">' + text + '</p>' for text in c['descriptions_html'])
    actions = []
    if partner.get('phone'):
        actions.append(f'<a href="tel:{escape(partner["phone"])}">{labels[5]}</a>')
    if partner.get('address'):
        actions.append(f'<a href="https://www.google.com/maps/search/?api=1&amp;query={quote(partner["address"], safe="")}" data-map-address="{escape(partner["address"], quote=True)}" target="_blank" rel="noopener noreferrer">{labels[6]}</a>')
    link_label = 'Instagram' if 'instagram.com/' in partner['url'] else labels[7]
    actions.append(f'<a href="{escape(partner["url"], quote=True)}" target="_blank" rel="noopener noreferrer">{link_label}</a>')
    return f'''            <article class="partner-card" data-category="{escape(partner.get('category', ''))}">
              <div class="partner-card__image">{c['image_html']}</div>
              <div class="partner-card__content"><h2 id="title-{ident}" class="partner-card__title">{title}</h2><span class="partner-card__city">{escape(partner.get('city', ''))}</span></div>
              <button class="partner-card__open" type="button" data-partner="{ident}" aria-labelledby="title-{ident}" aria-haspopup="dialog" aria-controls="partner-dialog"></button>
              <template id="partner-{ident}">
                <div class="partner-card__image">{c['image_html']}</div>
                <div class="partner-dialog__content"><h2 id="partner-dialog-title" class="partner-card__title">{title}</h2>
                  {paragraphs}
                  <div class="partner-dialog__actions">{''.join(actions)}</div>
                  <p class="partner-card__badge">{escape(c['badge'])}</p>
                </div>
              </template>
            </article>'''


def controls(lang):
    labels = LABELS[lang]
    filters = ''.join(f'<button type="button" data-filter="{key}" aria-pressed="{str(key == "all").lower()}">{label}</button>' for key, label in zip(['all', 'salons', 'clinics', 'business'], labels[:4]))
    return f'''          <!-- Partner controls -->
          <div class="partners-filters">{filters}</div>
          <dialog id="partner-dialog" class="partner-dialog" aria-labelledby="partner-dialog-title">
            <button type="button" class="partner-dialog__close" aria-label="{labels[4]}" autofocus>×</button>
            <div class="partner-dialog__body"></div>
          </dialog>
          <script src="/js/partners.js" defer></script>
          <!-- /Partner controls -->
'''


def build(check=False):
    data = load()
    partners = sorted(data['partners'], key=lambda p: p['priority'], reverse=True)
    stale = []
    for lang, filename in data['pages'].items():
        path = ROOT / filename
        source = path.read_text()
        source = re.sub(r'          <!-- Partner controls -->.*?          <!-- /Partner controls -->\n', '', source, flags=re.S)
        body = '\n            <!-- Generated by scripts/build-partners.py from scripts/partners.json. -->\n'
        body += '\n'.join(render(p, lang) for p in partners)
        updated, count = BLOCK.subn(lambda m: m['start'] + body + m['end'], source)
        assert count == 1, filename
        updated = updated.replace('          <div class="partners-grid">', controls(lang) + '          <div class="partners-grid">')

        if updated != path.read_text():
            stale.append(filename)
            if not check:
                path.write_text(updated)
    print(f'Partners: {len(partners)}; pages: {len(data["pages"])}; {"stale" if check else "updated"}: {len(stale)}')
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = build(args.check)
    if args.check and stale:
        raise SystemExit(1)
